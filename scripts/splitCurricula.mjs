import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { CARRERAS } from '../src/data/carreras.js'
const root = new URL('../', import.meta.url), check = process.argv.includes('--check')
mkdirSync(new URL('src/data/careers/', root), { recursive: true })
for (const [key, career] of Object.entries(CARRERAS)) {
 const target = new URL(`src/data/careers/${key}.js`, root), value = `// Generated by scripts/splitCurricula.mjs; public curriculum data.\nexport default ${JSON.stringify(career)}\n`
 if (check) { if (readFileSync(target,'utf8') !== value) throw new Error(`Regenerate ${key}`) }
 else writeFileSync(target, value)
}
const target = new URL('src/data/careerImports.js',root)
const value = '// Generated by scripts/splitCurricula.mjs. Literal imports preserve one chunk per career.\nexport const careerImports = {\n'+Object.keys(CARRERAS).map(key=>`  ${JSON.stringify(key)}: () => import('./careers/${key}.js')`).join(',\n')+'\n}\n'
if(check){if(readFileSync(target,'utf8')!==value)throw new Error('Regenerate career imports')}else writeFileSync(target,value)

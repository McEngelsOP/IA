import { CARRERAS } from '../src/institutions/esan/carreras.js'
import { readFileSync, writeFileSync } from 'node:fs'
const sql = s => "'"+s.replaceAll("'","''")+"'"
const target = new URL('../supabase/system_catalog_seed.sql', import.meta.url)
const statements = Object.values(CARRERAS).map(c => `update public.curriculum_versions set catalog=${sql(JSON.stringify(c))}::jsonb,published_at=coalesce(published_at,now()) where institution_id='esan' and career_key=${sql(c.key)} and version=${sql(c.version)} and catalog is null;`)
const output = ['-- Generated by scripts/systemCatalogSeed.mjs. Run manually after system_complete.sql.', '-- Fills missing catalogs only; existing published catalogs remain unchanged.', 'begin;', ...statements, 'commit;', ''].join('\n')
const mode = process.argv[2]
if (mode === '--write') {
  writeFileSync(target, output)
  console.log('SQL de los 18 catálogos preparado; no se ejecutó en ninguna base de datos.')
} else if (mode === '--check') {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Regenera system_catalog_seed.sql con node scripts/systemCatalogSeed.mjs --write')
  console.log('SQL de los 18 catálogos actualizado.')
} else if (mode) {
  throw new Error('Usa --write, --check o ningún argumento para imprimir el SQL.')
} else {
  process.stdout.write(output)
}
